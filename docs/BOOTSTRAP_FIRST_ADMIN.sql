-- BOOTSTRAP_FIRST_ADMIN.sql
-- 师创「开第一道门」脚本 —— 部署后必须跑一次，否则谁都登不进去。
--
-- 为什么需要它：
--   平台是「邮箱 + 密码 + 邀请码」自助注册（见 0002 handle_new_user 触发器，
--   注册必须填 kind='invite' 的邀请码）。而邀请码只能管理员在后台生成
--   （0009 make_redemption_codes 校验 role='admin'）。但管理员账号也得先注册才有，
--   又没人能生成第一个邀请码 → 卡死。迁移里没有种子管理员 / 种子邀请码，
--   所以上线后第一件事是用本脚本开这第一道门。
--
-- 谁跑：野马（平台 owner），在 Supabase 后台 → SQL Editor 粘贴执行。
-- 前置：0001–0031 迁移已跑完、SILICONFLOW_API_KEY 已就绪。
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Step 1：插入一个「引导邀请码」（owner 自己注册用，仅一次）
--   说明：code 任意大写串即可（触发器不校验格式，只校验是否存在且未用）。
--   这里用 SHICHUANG；credits=100 即注册赠送 100 积分；valid_days=0 不过期。
--   on conflict 保证重复执行幂等（不会报错）。
-- ---------------------------------------------------------------------------
insert into public.redemption_codes (code, kind, credits, status, batch_no, memo)
values ('SHICHUANG', 'invite', 100, 'unused', 'BOOTSTRAP', '初始管理员引导码')
on conflict (code) do nothing;

-- ---------------------------------------------------------------------------
-- Step 2：注册你的账号
--   方式 A（推荐，需能打开网站）：浏览器开 https://yemabuye11.github.io/shichuang/
--     （国内 github.io 常被墙，用手机流量/梯子打开），点「注册」，填：
--       邮箱 = 你自己的邮箱
--       密码 = 至少 8 位
--       邀请码 = SHICHUANG
--     → 建好普通账号，自动获赠 100 积分。此时你还是普通用户，不是管理员。
--
--   方式 B（打不开网站时）：Supabase 后台 → Authentication → Users → Add user
--     填邮箱 + 密码，并在 User Metadata 填：{"invite_code": "SHICHUANG", "nickname": "野马"}
--     → 触发器会建 profile 并核销该邀请码（同方式 A 的效果）。
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- Step 3：把你升为管理员（把下面邮箱换成你刚注册的那个）
--   注意：profile.role 默认是 'user'，没有任何迁移会自动设 admin，必须手动升。
--   升完后退出重登（让前端刷新角色），后台即出现「管理员」入口。
-- ---------------------------------------------------------------------------
update public.profiles
set role = 'admin'
where id = (select id from auth.users where email = '你注册的邮箱');

