-- 文档生成提示词：补「内容下限」+ 解除对图的自我封印
--
-- 背景（客户原话：「课件生成质量太简陋，要提升到可直接对外展示的水准」）：
--   经排查，质量差不是模型能力问题，也不是钱的问题，而是**提示词只约束了上限、
--   没约束下限**，外加**提示词自己把图关掉了**。两处缺口如下：
--
-- 缺口 1：只有「最多写多少」，没有「最少写多少」
--   0024 已把 system_config.limit.maxOutputTokens 从 8000 放宽到 16000，
--   但 prompt_templates 里**没有任何量化下限**：模型按"够用就行"输出，
--   于是拿到 16000 token 的空间却只写 3000 token 的骨架。
--   → 本文件给 教案 / PPT / 课件2D / 办公文档 各自补上可检查的量化下限
--     （条数 / 字数 / 页数 / 块数），并显式禁止占位符与施工标记。
--
-- 缺口 2：图被提示词自己禁掉了（**且至今仍在生效**）
--   0024 的 `system_section:doc_output_format` 第 4 条写着：
--     `type` 只能取 `heading` / `paragraph` / `list` / `table` / `image` / `callout`
--   ——**没有 `chart`**。而 0026（chart 块）与 0028（教案高阶）都要求模型"必须用
--   chart 块出图"，且 doc_output_format 在 compose.ts 里**排在 doc_type:<kind> 之前**
--   （见 DOC_SYSTEM_SECTIONS 数组顺序）。于是同一份 system 提示里：
--     前面说「type 不能是 chart」→ 后面说「必须输出 chart 块」
--   模型遇到自相矛盾的硬约束（前者还是"违反即判定失败"），倾向于保守地不输出 chart。
--   → 本文件把 `chart` 补进合法 type 列表，并写清 chart / image 的使用规则。
--
--   补充说明（避免误解）：
--     - 0026 / 0028 已经把 `doc_type:lesson_plan` / `ppt` / `courseware_2d` 三份里
--       的「image.src 留空，注明建议配图」改掉了，所以那三处**不需要再改**；
--       真正残留的封印在 `system_section:doc_output_format`（本文件一并修掉）。
--     - 全仓库**不存在任何文生图能力**（已确认：无 images/generations 类调用）。
--       因此"真实可用的图"只能是：① `chart` 块（平台用内联 SVG 真渲染，
--       见 `_shared/doc/render.ts` renderChartSvg）；② `image` 块的 data URI 内联 SVG。
--       本文件按这个事实给规则，不要求模型编造图片 URL。
--
-- 本文件只改配置表（prompt_templates），**不需要重新部署 Edge Function**（60s 缓存后生效）。
-- 明确不涉及：积分/价格（app_type_profiles.credit_cost、system_config 价格项）、
--           3D 相关（doc_type:courseware_3d 保持 0027 版本不动）、前端 src/。
-- =============================================================================

-- ---------------------------------------------------------------------------
-- 幂等 seed 助手（与 0011 / 0016 / 0023 / 0024 / 0026 / 0027 / 0028 同实现）
--   行为：同 key 旧版本全部置为 is_active=false，插入新版本并激活。
--   幂等性：可反复执行，不报错；每次执行会新增一个版本行（version+1），
--           旧版本保留为历史快照，不删除。客户在 SQL Editor 里重复粘贴安全。
-- ---------------------------------------------------------------------------
create or replace function public.seed_prompt(
  p_kind    text,
  p_key     text,
  p_content text,
  p_by      uuid default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_version integer := 1;
begin
  select coalesce(max(version), 0) into v_version
    from public.prompt_templates
   where key = p_key;

  if v_version > 0 then
    v_version := v_version + 1;
  end if;

  update public.prompt_templates set is_active = false where key = p_key;

  insert into public.prompt_templates (kind, key, version, content, is_active, created_by)
  values (p_kind, p_key, v_version, p_content, true, p_by)
  on conflict do nothing;
end;
$$;

