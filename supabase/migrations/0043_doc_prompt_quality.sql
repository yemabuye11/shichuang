## 图怎么出（这是"课件里真的有图"的唯一途径，务必看完）

平台**没有文生图能力**，但有两条能画出真图的路径，按优先级使用：

### 路径 A（首选）：`chart` 块 —— 平台用内联 SVG 真渲染
网页、导出、打印三处都能显示。**凡涉及函数、数据、统计、趋势、对比，一律走这条路。**

```
{
  "id": "c1",
  "type": "chart",
  "chart": {
    "kind": "function",
    "expression": "y = x^2 - 2x - 3",
    "xLabel": "x",
    "yLabel": "y",
    "points": [[-2,5],[-1,0],[0,-3],[1,-4],[2,-3],[3,0],[4,5]]
  },
  "caption": "图1 二次函数 y=x^2-2x-3 的图像：开口向上，对称轴 x=1，顶点 (1,-4)"
}
```

- `kind='function'`（函数图像 / 几何描点）：给 `expression` + **12~25 个** `[x,y]` 采样点，
  取值范围必须能看出图像特征（含顶点、零点、与坐标轴交点）。
- `kind='bar'`（分类对比 / 统计）：给 `categories`（分类名数组）+ `values`（数值数组）。
- `kind='line'`（变化趋势）：给 `points`。
- `caption` 必须写清**这张图说明了什么**（顶点、交点、最值、趋势），不能只写"如图所示"。
- 关键取值（顶点、零点、截距）另外再用 `table` 或 `list` 列一份，方便教师板书。

### 路径 B（仅当 chart 表达不了时）：`image` 块 + 内联 SVG 的 data URI
例如实验装置、地理示意、生物结构这类**示意图**。此时 `src` 必须是**可直接渲染的
data URI**，不允许留空。

```
{
  "id": "i1",
  "type": "image",
  "src": "data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 400 240'%3E%3Crect width='400' height='240' fill='%23F7F9FC'/%3E%3Cline x1='40' y1='200' x2='360' y2='200' stroke='%231B1F27' stroke-width='2'/%3E%3Ccircle cx='200' cy='120' r='60' fill='none' stroke='%232F6BFF' stroke-width='3'/%3E%3Ctext x='200' y='228' text-anchor='middle' font-size='14' fill='%236B7280'%3EFig.1%3C/text%3E%3C/svg%3E",
  "caption": "图2 实验装置示意图（烧杯、铁架台、酒精灯的位置关系）"
}
```

编码规则（必须逐条遵守，否则图会显示不出来）：
- `<` → `%3C`，`>` → `%3E`，`#` → `%23`，`"` 一律写成单引号 `'`；
- SVG 里**不要写中文**（编码容易出错），只用图形 + 数字 / 字母标注，说明写进 `caption`；
- 图形保持简单（矩形 / 圆 / 线 / 箭头 / 少量文字），不要把整页板书塞进一张 SVG。

### ❌ 明确禁止
- **禁止**输出 `src` 为空、空字符串、或写着"待补 / 建议配图 / 略"的 `image` 块——
  那渲染出来只是一个虚线框，等于没有图。
- **禁止**编造外部图片 URL（如 `https://example.com/xxx.png`）——平台离线可用，
  外链图片在教室电脑上一定加载失败。
- 拿不准 `src` 能不能渲染时，**不要输出 `image` 块**：改用 `table`（列出关键坐标 / 部件 /
  数值）或 `list`（分步描述图形结构），把同样的信息**完整**表达出来。

