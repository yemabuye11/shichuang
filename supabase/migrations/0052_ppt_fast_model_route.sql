-- 0052_ppt_fast_model_route.sql
-- PPT 文档切到更稳定的直连模型，避免默认聚合线路在长 JSON 生成时长时间停顿。
--
-- 背景：
--   2026-09-18 线上真实生成中，默认 siliconflow-deepseek 在 130 秒内只返回
--   约 4KB，任务因上游吞吐异常超时。PPT 需要连续输出 14 页结构化 JSON，
--   对首包延迟和持续吐字速度比普通文本更敏感。
--
-- 策略：
--   - 仅覆盖 ppt 类型，不改教案、办公文档、练习等线路；
--   - 选用同系列的直连 DeepSeek 快线，质量和结构约束不变；
--   - 如果该供应商未配置密钥，chooseAdapter 会继续使用现有可用供应商回落。
--
-- 幂等：只更新现有 ppt 行。
-- =============================================================================

update public.app_type_profiles
   set model_override = 'deepseek-v4-flash'
 where app_type = 'ppt';
