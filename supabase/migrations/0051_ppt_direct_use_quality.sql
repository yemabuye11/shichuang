## 一、固定 14 页，形成完整课堂流程

`slides` 必须正好输出 **14 页**，顺序如下：

1. 封面（layout=title）：课题、学科年级、教材课时、课堂时长。
2. 学习目标：学生能做什么，避免“了解、掌握”空话，给出可观察目标。
3. 情境导入：一个真实问题、图片线索或生活情境，并写出教师提问。
4. 初读任务：朗读、圈画、标段或提取信息的明确动作。
5. 字词 / 概念理解：把本课必须解决的生字、词语或核心概念讲清楚。
6. 知识讲解 1：核心概念、定义、规则或阅读方法。
7. 知识讲解 2：关键特征、结构、语言现象或难点，必须配真实图示。
8. 例题示范：完整展示一步，步骤不能跳。
9. 跟着做 / 课堂活动：同桌或小组任务，明确任务、时间与汇报方式。
10. 易错提醒：列 2~3 个真实错误，并给出纠正句。
11. 当堂练习：至少 3 题，包含基础题和一道稍有挑战的题。
12. 迁移应用：把知识用到新题、新语段、新材料或新生活情境。
13. 课堂小结：用结构图或要点清单回收本课学习路径。
14. 作业布置：基础、提高、挑战三层，写清提交要求。

如需微调标题，可以调整，但**不能少页、不能把多页合并，也不能复制同一页换标题充数**。

---

## 二、每页都要能直接投屏讲解

- 每页 `body` 保留 2~4 个结构化块，避免整页只有一大段文字。
- 内容页至少承担一个明确的课堂动作：讲解、提问、示范、练习、讨论、纠错或检测。
- 列表写可直接板书或投屏的短句；表格保留真实对比、步骤、取值或答案要点。
- `callout` 用来突出“教师提醒”“学生易错”“思考方向”，每节课 2~4 个即可。
- `notes` 写 **45~100 字**的教师口播稿，包含：
  - 教师可以直接照着说的开场或过渡语；
  - 一个关键问题；
  - 学生可能回答 / 易错点以及教师追问。
- 禁止“完成对应练习”“教师可自行补充”“略”“同上”“此处展开”等空话。

---

## 三、必须有真实教学图示

「图」只认 `chart` 和 `image`。`src` 为空、外链图片或“建议配图：XX”
都等于没有图。

### 数据型课题

数学、物理、化学、生物、地理、信息技术，以及任何以数据、函数、实验、统计、
趋势、占比、结构或对比为主的课题：

- 整份至少 **6 个真实图示**；
- 其中至少 **3 个 `chart`**；
- 函数、变化趋势、分类比较、实验数据必须用 `chart`，不能只写成文字表格；
- 知识讲解、例题、练习页优先配图，封面和作业页可以无图。

### 语文、历史、政治、英语等文科课题

- 整份至少 **4 个有信息量的 `image` 教学图示**；
- 可选图示包括：时间轴、诗句画面、文章结构图、人物关系图、情节推进图、
  论证结构图、词语辨析卡、朗读节奏图；
- 图示必须帮助理解内容，不能画云朵、圆圈、星星等纯装饰图；
- `image.src` 使用内联 SVG data URI，图形保持简洁，说明写进 `caption`；
- SVG 中优先使用线条、矩形、编号和少量字母；不要塞入大段文字。
- 图示中的可见文字必须使用中文；禁止 `Water Cycle`、`Evaporation` 等英文标签。

