## 四、版式与信息节奏

- 封面、章节页使用 `title` / `section`，其余使用 `content` 或 `two_col`。
- 有图页优先使用 `content`，让文字与图形成左右主次。
- 对比、两首诗、两种方法、两种解法使用 `two_col`。
- 不要连续 3 页都是同一种“标题 + 文字列表”结构；至少加入图示、表格、
  对比栏或活动页。
- 字号与留白优先服务课堂投屏：每页只讲清楚一个教学动作，不堆满长段文字。
- 表格表头字段统一写 `header`，禁止写成 `headers` 或 `columns`；
  `callout` 只使用 `text`，禁止自造 `title` 字段。

