-- =============================================================================
-- 0053_ppt_18_page_direct_use.sql
-- 在不牺牲 JSON 完整性的前提下，把 PPT 课堂流程从 14 页扩展到 18 页。
--
-- 背景：
--   14 页能覆盖基本闭环，但练习、讨论、方法归纳和教师机动提示容易被压缩。
--   本次把主目标调整为 18 页，并保留 16 页最低修复线；Edge Function 的
--   动态输出预算仍是最高优先级，避免数据库提示词中的扩展建议造成超时。
-- =============================================================================

update public.prompt_templates
   set content = replace(
     replace(
       replace(
         replace(
           content,
           '## 一、固定 14 页，形成完整课堂流程',
           '## 一、固定 18 页，形成完整课堂流程'
         ),
         '14. 作业布置：基础、提高、挑战三层，写清提交要求。',
         E'14. 基础练习：至少 3 题，面向全班，明确检查方式。\n15. 提高练习：1~2 题，突出本课易错点或方法迁移。\n16. 课堂讨论：给出有争议或可比较的问题，明确讨论与汇报方式。\n17. 方法归纳：用结构图或步骤清单总结可迁移的方法。\n18. 课堂小结与作业：回收学习路径，作业分基础、提高、挑战三层；末尾写教师核对与课上机动提示。'
       ),
       '`slides` 必须正好输出 **14 页**，顺序如下：',
       '`slides` 必须正好输出 **18 页**，顺序如下：'
     ),
     '不能少页、不能把多页合并，也不能复制同一页换标题充数。',
     '不能少页、不能把多页合并，也不能复制同一页换标题充数。'
   )
 where key = 'doc_type:ppt'
   and is_active;
